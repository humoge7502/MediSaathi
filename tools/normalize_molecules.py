"""Collapse split molecule identities onto one canonical name (ADR-0012, MED-027).

Measured before this tool existed (all numbers are counts of *rows* whose
molecule cell changes, read back from the loaded tables, not estimated):

    brands.csv            23 rows named a drug by its salt or a variant spelling
    interactions.csv      84 rows
    contraindications.csv 17 rows
    dose_caps.csv          3 rows        (renamed by the generator, see below)
    rxnorm_molecule_map    2 rows

The consequence is not cosmetic. What those 23 brand rows could actually reach,
before and after, is measured by `--reach` and frozen in
`data/reference/molecule_identity_reach.json` — the before half is only
computable from the backup snapshot the governed importer leaves behind, so the
numbers are written to an artifact with their definition instead of being
retyped from a terminal:

    interaction rows reachable            561 -> 1,475
    contraindication rows reachable        38 ->     72
    brand rows reaching a daily ceiling     0 ->     23   (of 23)

Three of the failures, read back out of the tables rather than reasoned about:

  - "carvedilol phosphate" reached 0 interaction rows; "carvedilol" reaches 28.
    It reached 4 contraindications; "carvedilol" has 5, and two of those are
    ABSOLUTE for something the phosphate row never mentions (bradycardia,
    heart_block). So the Jan Aushadhi carvedilol ER brands screened no
    interaction and no heart-block rule at all.
  - "lithium carbonate" reached 4 contraindications, none of them pregnancy.
    "lithium" reaches 3, two of them ABSOLUTE — pregnancy (Ebstein anomaly) and
    lactation — plus the 2400 mg daily cap. Same salt, same drug, one lookup
    table, two answers.
  - "cyclosporin" reached 0 of cyclosporine's 164 interaction rows, and
    "torsemide" 0 of torasemide's 109.

Those counts are the two halves each drug was split into; read as one identity
after the merge, carvedilol holds 28 interaction rows and 7 contraindications (3
ABSOLUTE) and lithium holds 7 contraindications (3 ABSOLUTE) plus its 2400 mg
ceiling — the numbers above are what each half could not see on its own.

Renaming is a data mutation, so it goes through the governed path: the three
primary tables are applied with `tools/import_snapshot.py --apply`, which
validates the schema, hashes, diffs and leaves a provenance report; a `.bak` of
the previous file is kept by that tool. `rxnorm_molecule_map.csv` has no schema
tool, so this one backs it up itself.

Collisions are adjudicated, never dropped silently. The single pass over the
pre-migration tables found 13 interaction pairs, 5 contraindication keys and 1
dose cap stated twice — the same clinical claim written under both names. The
survivor is the *stronger or better-sourced* statement of it: severity first,
then an escalating cap over an advisory one, then a row that states the
mechanism over a row that only cites a page, then a curated adjudication, then
the longer text. A merge therefore cannot weaken a rule, and four of them
corrected one upward — metronidazole + lithium was stated `severe` under one
identity and `moderate` under the other. Every dropped row is kept verbatim in
`data/reference/molecule_merges.csv`, citation included, so a reviewer can
disagree with a survivor.

dose_caps.csv is generated by `tools/build_dose_caps.py` and drift-tested, so
this tool audits it and the generator renames it, both through this one table.

Explicit non-merges, pinned by a test in `apps/api/tests/test_molecule_identity.py`:
citalopram is not escitalopram, omeprazole is not esomeprazole, prednisone is not
prednisolone, and sodium chloride / potassium chloride / calcium carbonate are
three different drugs that a suffix-stripping rule would happily have merged
into the empty string. This table is curated chemistry, not fuzzy matching.

Run:  python tools/normalize_molecules.py           (dry run: report only)
      python tools/normalize_molecules.py --apply   (mutate the live tables)
      python tools/normalize_molecules.py --check   (gate: no alias name survives)
      python tools/normalize_molecules.py --reach   (freeze the before/after evidence)
"""
from __future__ import annotations

import csv
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
STAGING = os.path.join(ROOT, "data", ".staging")

# alias -> (canonical, basis, source). Basis is why these two names are one
# substance; it is written into the audit file so a reviewer can disagree.
ALIASES: dict[str, tuple[str, str, str]] = {
    "lithium carbonate": ("lithium", "salt of the same active ion (Li+)",
                          "RxNorm 6448 'Lithium Carbonate' -> preferred 'Lithium'"),
    "carvedilol phosphate": ("carvedilol", "soluble salt form of the same base",
                             "FDA label: Coreg = carvedilol; phosphate is the oral solution salt"),
    "clindamycin phosphate": ("clindamycin", "phosphate ester hydrolysed to the active base",
                              "FDA label: topical/oral phosphate is a pro-moiety of clindamycin"),
    "oseltamivir phosphate": ("oseltamivir", "phosphate salt of the active carboxylate",
                              "FDA label: Tamiflu is oseltamivir phosphate, dosing stated as oseltamivir"),
    "oxybutynin chloride": ("oxybutynin", "hydrochloride salt of the same base",
                            "FDA label: Ditropan = oxybutynin chloride"),
    "primaquine phosphate": ("primaquine", "phosphate salt of the same base",
                             "FDA label: primaquine phosphate, doses stated as primaquine base"),
    "betamethasone sodium phosphate": ("betamethasone", "soluble phosphate ester of the same steroid",
                                       "FDA label: betamethasone sodium phosphate injectable, dosed as betamethasone"),
    "ferrous sulphate": ("ferrous sulfate", "British vs US spelling of the same salt",
                         "INN/USAN spelling variant"),
    "cyclosporin": ("cyclosporine", "British name vs US adopted name of the same peptide",
                    "BAN 2023: cyclosporin renamed cyclosporine; one substance"),
    "torsemide": ("torasemide", "USAN vs INN spelling of the same loop diuretic",
                  "the formulary and MOLECULE_GROUPS already use torasemide"),
    "vitamin d3": ("cholecalciferol", "vitamin D3 IS cholecalciferol",
                   "British Pharmacopoeia / USP synonym list"),
}

SEVERITY_RANK = {"mild": 0, "relative": 0, "moderate": 1, "severe": 2, "absolute": 2}

# Pairs a suffix-stripping or fuzzy matcher would merge and this table refuses
# to. Every entry is pinned by apps/api/tests/test_molecule_identity.py, because
# "it looked like a typo" is not a reason to collapse two different drugs.
NOT_MERGED: tuple[tuple[str, str, str], ...] = (
    ("citalopram", "escitalopram",
     "racemate vs its pure S-enantiomer: different drug, different QT liability"),
    ("omeprazole", "esomeprazole",
     "racemate vs its S-enantiomer: different drug"),
    ("prednisone", "prednisolone",
     "prodrug vs active metabolite: not interchangeable in hepatic failure"),
    ("sodium chloride", "potassium chloride",
     "suffix stripping would join two different electrolytes"),
    ("calcium carbonate", "sodium chloride",
     "suffix stripping would collapse three different salts onto ''"),
)


def canonical(molecule: str) -> str:
    """Component-wise canonical name, lowercased, combination order preserved."""
    parts = [p.strip() for p in (molecule or "").split("+") if p.strip()]
    return "+".join(ALIASES.get(p.lower(), (p.lower(),))[0] for p in parts)


class Table:
    def __init__(self, rel: str, cols: tuple[str, ...], key: tuple[str, ...],
                 kind: str | None, text_cols: tuple[str, ...] = (),
                 unordered: bool = False) -> None:
        self.rel = rel
        self.path = os.path.join(ROOT, rel)
        self.cols = cols
        self.key = key
        self.kind = kind          # import_snapshot kind, or None for reference tables
        self.text_cols = text_cols
        # `unordered` means the key identifies a SET, not an ordered tuple,
        # because that is how the engine indexes it: interactions_by_pair uses
        # frozenset, so (warfarin, aspirin) and (aspirin, warfarin) are one rule.
        # Without this, 9 of the 13 collisions the rename creates stay in the
        # file as two rows on one engine key and the loader keeps whichever came
        # last — which is how metronidazole + lithium ended up stated twice, at
        # `severe` one way round and `moderate` the other. Measured on the
        # pre-migration file: 0 duplicate engine keys, so every collision here is
        # the same rule written under both identities, not junk to discard.
        self.unordered = unordered

    def row_key(self, row: dict) -> tuple:
        parts = [((row.get(c) or "").strip().lower()) for c in self.key]
        return tuple(sorted(parts)) if self.unordered else tuple(parts)


TABLES = [
    Table("data/brands.csv", ("molecule",), ("brand",), "brands"),
    Table("data/interactions.csv", ("molecule_a", "molecule_b"),
          ("molecule_a", "molecule_b"), "interactions", ("mechanism",),
          unordered=True),
    Table("data/contraindications.csv", ("molecule", "condition_code"),
          ("molecule", "condition_code"), "contraindications", ("note",)),
    Table("data/reference/rxnorm_molecule_map.csv", ("molecule",), ("molecule",), None),
]

# dose_caps.csv is GENERATED by tools/build_dose_caps.py, which now canonicalizes
# through this same table. Writing it here would be overwritten on the next
# regeneration, so the generator owns it and this tool only audits it.
AUDIT_ONLY = [
    Table("data/reference/dose_caps.csv", ("molecule",), ("molecule",), None, ("note",)),
]

ALIASES_PATH = os.path.join(ROOT, "data", "reference", "molecule_aliases.csv")
REACH_PATH = os.path.join(ROOT, "data", "reference", "molecule_identity_reach.json")

#: Stated once, in the artifact, so the number can be re-derived or argued with
#: instead of being read as folklore.
REACH_DEFINITION = (
    "For each brand row whose molecule cell the rename changed: the rules it can "
    "reach are those whose molecule key is one of the row's identities (each "
    "component, and the whole string for a combination). Summed over those rows; "
    "'before' reads the pre-migration tables kept by the governed importer as "
    "<table>.bak, 'after' reads the live ones. Ceilings are counted as brands "
    "reaching at least one daily-dose cap, against the live cap table, under the "
    "old spelling versus the canonical one."
)


def _identities(name: str) -> set[str]:
    parts = [p.strip().lower() for p in (name or "").split("+") if p.strip()]
    return set(parts) | {"+".join(parts)}


def _backup_of(path: str) -> str | None:
    """The pre-migration copy, whichever backup mechanism wrote it."""
    for candidate in (path + ".bak", path + ".before-molecule-normalize"):
        if os.path.exists(candidate):
            return candidate
    return None


def measure_reach() -> int:
    """Freeze what the identity law buys, so the README cites an artifact.

    The before half is only measurable once — the backup snapshot is overwritten
    by the next migration — which is exactly why it must not live in prose.
    """
    brands = os.path.join(ROOT, "data", "brands.csv")
    pre_path = _backup_of(brands)
    if not pre_path:
        print("no pre-migration brands.csv backup to measure against; the recorded "
              f"numbers are in {os.path.relpath(REACH_PATH, ROOT)}", file=sys.stderr)
        return 0
    _, pre_brands = _read(pre_path)
    _, post_brands = _read(brands)
    affected = [r for r in pre_brands
                if canonical(r["molecule"]) != r["molecule"].strip().lower()]
    post_by_brand = {r["brand"]: r["molecule"] for r in post_brands}

    def index(rows: list[dict], cols: tuple[str, ...]) -> dict[str, set[int]]:
        out: dict[str, set[int]] = {}
        for n, row in enumerate(rows):
            for col in cols:
                out.setdefault((row.get(col) or "").strip().lower(), set()).add(n)
        return out

    def counted(table: Table) -> dict[str, int]:
        backup = _backup_of(table.path)
        if not backup:
            return {}
        _, pre_rows = _read(backup)
        _, live_rows = _read(table.path)
        before = index(pre_rows, table.cols)
        after = index(live_rows, table.cols)
        s_b = s_a = 0
        for row in affected:
            # `affected` is never empty here, and a molecule cell always has at
            # least one identity, so the unions below always have an operand.
            hits_b = set().union(*(before.get(k, set()) for k in _identities(row["molecule"])))
            name = post_by_brand.get(row["brand"], canonical(row["molecule"]))
            hits_a = set().union(*(after.get(k, set()) for k in _identities(name)))
            s_b += len(hits_b)
            s_a += len(hits_a)
        return {"before": s_b, "after": s_a,
                "pre_rows": len(pre_rows), "live_rows": len(live_rows)}

    _, cap_rows = _read(os.path.join(ROOT, "data", "reference", "dose_caps.csv"))
    caps = {r["molecule"].strip().lower() for r in cap_rows}
    reach_before = sum(1 for r in affected if _identities(r["molecule"]) & caps)
    reach_after = sum(1 for r in affected
                      if _identities(canonical(r["molecule"])) & caps)

    cells = {}
    for table in TABLES:
        backup = _backup_of(table.path)
        if not backup:
            continue
        _, pre_rows = _read(backup)
        cells[os.path.relpath(table.path, ROOT).replace(os.sep, "/")] = sum(
            1 for r in pre_rows
            if any(canonical(r[c]) != (r[c] or "").strip().lower() for c in table.cols))

    out = {
        "definition": REACH_DEFINITION,
        "measured_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "affected_brand_rows": len(affected),
        "aliases_retired": len(ALIASES),
        "cells_renamed": cells,
        "rules_reachable": {
            "interactions": counted(TABLES[1]),
            "contraindications": counted(TABLES[2]),
        },
        "brands_reaching_a_daily_cap": {"before": reach_before, "after": reach_after,
                                        "of": len(affected)},
    }
    with open(REACH_PATH, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"molecule identity reach written: {os.path.relpath(REACH_PATH, ROOT)}")
    for k, v in out["rules_reachable"].items():
        print(f"  {k}: {v.get('before')} -> {v.get('after')}")
    print(f"  brands reaching a ceiling: {reach_before} -> {reach_after} of {len(affected)}")
    return 0


def _read(path: str) -> tuple[list[str], list[dict]]:
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        return list(reader.fieldnames or []), [dict(r) for r in reader]


STUB_MARKERS = (
    "[fda spl:",            # a raw label excerpt, truncated mid-word with "..."
    "documented mild-level interaction",
    "documented moderate-level interaction",
    "documented severe-level interaction",
    "documented minor-level interaction",
)


def _states_content(table: Table, row: dict) -> int:
    """1 if the row says the clinical thing, 0 if it only points at a source.

    Measured, not assumed: the contraindication rows carrying a `[FDA SPL:…]`
    excerpt are literal truncations ("…rmanent pacemaker is in place") and they
    are LONGER than the authored one-line rule for the same drug and the same
    condition. Ranking on length alone therefore kept the garbled quote and
    dropped the usable sentence — for carvedilol/heart_failure and
    primaquine/pregnancy both. Content beats length.
    """
    text = " ".join((row.get(c) or "") for c in table.text_cols).lower()
    if not text:
        return 1
    return 0 if any(m in text for m in STUB_MARKERS) else 1


def _rank(table: Table, row: dict) -> tuple:
    """Sort key for 'the stronger or better-sourced statement wins'.

    Order: severity, then an escalating cap over an advisory one, then a row that
    states the mechanism over a row that cites a page, then a curated
    adjudication, then the longer text. A merge therefore cannot weaken a rule
    and cannot lose the clinical content.
    """
    if "severity" in row:
        rank = SEVERITY_RANK.get((row.get("severity") or "").strip().lower(), -1)
    elif "escalate" in row:
        # an escalating cap outranks an advisory-only one
        rank = 3 if (row.get("escalate") or "").strip().lower() == "true" else 1
    else:
        rank = 0
    content = _states_content(table, row)
    adjudicated = 1 if (row.get("review_status") or "").strip() == "adjudicated" else 0
    text = max((len(row.get(c) or "") for c in table.text_cols), default=0)
    return (rank, content, adjudicated, text)


def transform(table: Table, rows: list[dict]) -> tuple[list[dict], dict]:
    """Rename molecule columns, then merge any rows the rename made duplicates."""
    renamed = 0
    was_named: dict[int, str] = {id(r): " / ".join(r.get(c) or "" for c in table.cols)
                                 for r in rows}
    for row in rows:
        for col in table.cols:
            before = row.get(col) or ""
            after = canonical(before)
            if after != before.strip().lower():
                row[col] = after
                renamed += 1

    by_key: dict[tuple, dict] = {}
    merged: list[dict] = []
    dropped: set[int] = set()
    for row in rows:
        k = table.row_key(row)
        if k not in by_key:
            by_key[k] = row
            continue
        keep, lose = ((row, by_key[k]) if _rank(table, row) > _rank(table, by_key[k])
                      else (by_key[k], row))
        by_key[k] = keep
        merged.append({
            "key": list(k), "kept": _why(table, keep), "dropped": _why(table, lose),
            "kept_name": was_named[id(keep)], "dropped_name": was_named[id(lose)],
            "kept_row": json.dumps(keep, ensure_ascii=False, sort_keys=True),
            "dropped_row": json.dumps(lose, ensure_ascii=False, sort_keys=True),
        })
        dropped.add(id(lose))
    ordered = [r for r in rows if id(r) not in dropped]
    return ordered, {"renamed_cells": renamed, "rows_out": len(ordered),
                     "collisions": merged}


def _why(table: Table, row: dict) -> str:
    sev = (row.get("severity") or row.get("escalate") or "?").strip()
    label = next((row.get(c) for c in table.text_cols if (row.get(c) or "")), "")
    return f"{sev}:{len(label or '')}ch"


def _alias_leftovers() -> list[str]:
    """Every molecule cell in any audited table still named by a retired alias."""
    leftovers = []
    for table in TABLES + AUDIT_ONLY:
        if not os.path.exists(table.path):
            continue
        _, rows = _read(table.path)
        for row in rows:
            for col in table.cols:
                for part in (row.get(col) or "").split("+"):
                    if part.strip().lower() in ALIASES:
                        leftovers.append(f"{table.rel}:{col}={row.get(col)!r}")
    return leftovers


def main() -> int:
    apply_ = "--apply" in sys.argv
    check = "--check" in sys.argv

    if "--reach" in sys.argv:
        return measure_reach()

    if check:
        leftovers = _alias_leftovers()
        if leftovers:
            print(f"NOT NORMALIZED: {len(leftovers)} alias cell(s) remain", file=sys.stderr)
            for line in leftovers[:15]:
                print(f"  - {line}", file=sys.stderr)
            return 1
        print(f"molecule identity normalized: {len(TABLES) + len(AUDIT_ONLY)} tables, "
              f"{len(ALIASES)} aliases retired")
        return 0

    report = []
    for table in TABLES + AUDIT_ONLY:
        header, rows = _read(table.path)
        out_rows, stats = transform(table, rows)
        if table in AUDIT_ONLY:
            print(f"{table.rel}: {stats['renamed_cells']} cell(s) to rename, "
                  f"{len(rows)} -> {stats['rows_out']} rows, "
                  f"{len(stats['collisions'])} collision(s) — owned by "
                  f"tools/build_dose_caps.py, not written here")
            for c in stats["collisions"]:
                print(f"    {c['key']}: keep {c['kept_name']!r} ({c['kept']}), "
                  f"drop {c['dropped_name']!r} ({c['dropped']})")
            continue
        report.append((table, header, out_rows, stats))
        print(f"{table.rel}: {stats['renamed_cells']} cell(s) renamed, "
              f"{len(rows)} -> {stats['rows_out']} rows, "
              f"{len(stats['collisions'])} collision(s) adjudicated")
        for c in stats["collisions"]:
            print(f"    {c['key']}: keep {c['kept_name']!r} ({c['kept']}), "
                  f"drop {c['dropped_name']!r} ({c['dropped']})")

    if not apply_:
        print("\ndry run — pass --apply to write (the three primary tables go "
              "through tools/import_snapshot.py)")
        return 0

    os.makedirs(STAGING, exist_ok=True)
    for table, header, out_rows, _stats in report:
        if table.kind:
            cand = os.path.join(STAGING, f"{table.kind}.candidate.csv")
            with open(cand, "w", newline="", encoding="utf-8") as f:
                w = csv.DictWriter(f, fieldnames=header)
                w.writeheader()
                w.writerows(out_rows)
            cmd = [sys.executable, os.path.join(ROOT, "tools", "import_snapshot.py"),
                   "--kind", table.kind, "--source", cand, "--apply"]
            res = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
            print(res.stdout.strip() or res.stderr.strip())
            if res.returncode != 0:
                print(f"ABORTED at {table.kind}: the governed importer rejected the "
                      f"candidate. Tables already applied are live; fix and re-run "
                      f"(the tool is idempotent).", file=sys.stderr)
                return res.returncode
        else:
            backup = table.path + ".before-molecule-normalize"
            if not os.path.exists(backup):
                with open(table.path, encoding="utf-8") as src, open(backup, "w",
                                                                     encoding="utf-8",
                                                                     newline="") as dst:
                    dst.write(src.read())
            with open(table.path, "w", newline="", encoding="utf-8") as f:
                w = csv.DictWriter(f, fieldnames=header)
                w.writeheader()
                w.writerows(out_rows)
            print(f"{table.rel}: written (backup {os.path.basename(backup)})")

    # The alias table is loaded by both engines (data/reference/molecule_aliases.csv
    # -> apps/web/src/lib/safety/molecule-identity.generated.ts), so it is data
    # with a reviewer-facing reason on every row, not a constant in code.
    with open(ALIASES_PATH, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["alias", "canonical", "basis", "source", "merged"])
        for alias, (canon_name, basis, source) in sorted(ALIASES.items()):
            w.writerow([alias, canon_name, basis, source, "yes"])
        for a, b, reason in NOT_MERGED:
            for name in (a, b):
                w.writerow([name, name, reason, "curated chemistry: kept separate", "no"])
    print(f"alias table written: {os.path.relpath(ALIASES_PATH, ROOT)}")

    # Every row the rename collapsed, with both sides kept verbatim so a
    # clinician can disagree with the survivor.
    merges_path = os.path.join(ROOT, "data", "reference", "molecule_merges.csv")
    with open(merges_path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["table", "key", "kept_named", "dropped_named", "kept_row", "dropped_row"])
        for table, _, _, stats in report:
            for c in stats["collisions"]:
                w.writerow([table.rel, ";".join(c["key"]), c["kept_name"],
                            c["dropped_name"], c["kept_row"], c["dropped_row"]])
    print(f"merge audit written: {os.path.relpath(merges_path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
